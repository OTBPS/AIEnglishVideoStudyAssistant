"""Release bookkeeping: per-file manifests, deltas, and the release manifest.

Pure functions over directories and JSON, so they are unit-tested
(backend/tests/test_release_lib.py) and tools/build.py stays a thin script.

Artifacts per release (all in dist/release/):
  <Name>-<v>-files.json            every installed file: path, size, sha256.
                                   The *next* release diffs against it.
  <Name>-Setup-<v>.exe             full installer
  <Name>-Update-<old>-to-<v>.exe   delta installer (when a previous files.json exists)
  release-manifest.json            version + size + sha256 of every package
  SHA256SUMS.txt                   the same hashes in `sha256sum -c` format
"""

from __future__ import annotations

import hashlib
import json
import re
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

FILES_SCHEMA = 1
RELEASE_SCHEMA = 1
_CHUNK = 1 << 20
_SEMVER = re.compile(r"^\d+\.\d+\.\d+$")


@dataclass(frozen=True)
class FileEntry:
    path: str  # POSIX-style, relative to the install root
    size: int
    sha256: str


@dataclass(frozen=True)
class Delta:
    changed: tuple[str, ...]  # added or modified
    removed: tuple[str, ...]

    @property
    def empty(self) -> bool:
        return not self.changed and not self.removed


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while chunk := f.read(_CHUNK):
            h.update(chunk)
    return h.hexdigest()


def scan_tree(root: Path) -> dict[str, FileEntry]:
    entries: dict[str, FileEntry] = {}
    for p in sorted(root.rglob("*")):
        if p.is_file():
            rel = p.relative_to(root).as_posix()
            entries[rel] = FileEntry(rel, p.stat().st_size, sha256_file(p))
    return entries


def files_manifest(product: str, version: str, entries: dict[str, FileEntry]) -> dict[str, Any]:
    return {
        "schema": FILES_SCHEMA,
        "product": product,
        "version": version,
        "files": [vars(e) for e in sorted(entries.values(), key=lambda e: e.path)],
    }


def parse_files_manifest(doc: dict[str, Any], product: str) -> tuple[str, dict[str, FileEntry]]:
    if doc.get("schema") != FILES_SCHEMA:
        raise ValueError(f"unsupported files manifest schema {doc.get('schema')!r}")
    if doc.get("product") != product:
        raise ValueError(f"files manifest is for {doc.get('product')!r}, not {product!r}")
    version = doc.get("version")
    if not isinstance(version, str) or not _SEMVER.match(version):
        raise ValueError(f"bad version in files manifest: {version!r}")
    entries = {f["path"]: FileEntry(f["path"], int(f["size"]), f["sha256"]) for f in doc["files"]}
    return version, entries


def diff(old: dict[str, FileEntry], new: dict[str, FileEntry]) -> Delta:
    changed = tuple(p for p in sorted(new) if p not in old or old[p].sha256 != new[p].sha256)
    removed = tuple(p for p in sorted(old) if p not in new)
    return Delta(changed, removed)


def version_tuple(v: str) -> tuple[int, ...]:
    if not _SEMVER.match(v):
        raise ValueError(f"not X.Y.Z: {v!r}")
    return tuple(int(x) for x in v.split("."))


def _inno(path: str) -> str:
    """POSIX relative path -> Inno Setup path, with braces escaped."""
    return path.replace("/", "\\").replace("{", "{{")


def render_delta_iss(delta: Delta) -> str:
    """[Files] and [InstallDelete] sections for a delta installer."""
    lines = ["; GENERATED by tools/build.py -- do not edit.", "[Files]"]
    for rel in delta.changed:
        parent = rel.rpartition("/")[0]
        dest = "{app}" + ("\\" + _inno(parent) if parent else "")
        lines.append(
            f'Source: "{{#DistDir}}\\{_inno(rel)}"; DestDir: "{dest}"; Flags: ignoreversion'
        )
    lines.append("")
    lines.append("[InstallDelete]")
    lines.extend(f'Type: files; Name: "{{app}}\\{_inno(rel)}"' for rel in delta.removed)
    return "\n".join(lines) + "\n"


def package_entry(kind: str, path: Path, **extra: Any) -> dict[str, Any]:
    return {
        "kind": kind,
        "file": path.name,
        "size": path.stat().st_size,
        "sha256": sha256_file(path),
        **extra,
    }


def release_manifest(
    product: str, version: str, commit: str, packages: list[dict[str, Any]]
) -> dict[str, Any]:
    return {
        "schema": RELEASE_SCHEMA,
        "product": product,
        "version": version,
        "commit": commit,
        "created": datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "packages": packages,
    }


def sha256sums(packages: list[dict[str, Any]]) -> str:
    return "".join(f"{p['sha256']}  {p['file']}\n" for p in packages)


def write_json(path: Path, doc: dict[str, Any]) -> None:
    path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
