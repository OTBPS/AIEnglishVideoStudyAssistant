"""Propagate product.toml into the files that cannot read it themselves.

    python tools/sync_product.py           rewrite derived files
    python tools/sync_product.py --check   exit 1 if any derived file drifted

Derived files:
  extension/manifest.json   "version", "key", "name"
  extension/src/product.js  constants for the extension's JavaScript
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PRODUCT_TOML = ROOT / "product.toml"
MANIFEST = ROOT / "extension" / "manifest.json"
PRODUCT_JS = ROOT / "extension" / "src" / "product.js"


def load(path: Path = PRODUCT_TOML) -> dict[str, Any]:
    with path.open("rb") as f:
        return tomllib.load(f)


def render_manifest(product: dict[str, Any], current: dict[str, Any]) -> str:
    manifest = dict(current)
    manifest["name"] = product["product"]["name"]
    manifest["version"] = product["product"]["version"]
    manifest["key"] = product["extension"]["public_key"]
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def render_product_js(product: dict[str, Any]) -> str:
    p, r = product["product"], product["runtime"]
    consts = {
        "name": p["name"],
        "version": p["version"],
        "protocol": r["protocol"],
        "portFirst": r["port_first"],
        "portLast": r["port_last"],
    }
    body = json.dumps(consts, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by tools/sync_product.py from product.toml -- do not edit.\n"
        f"export const PRODUCT = Object.freeze({body});\n"
    )


def derived(product: dict[str, Any]) -> dict[Path, str]:
    current = json.loads(MANIFEST.read_text(encoding="utf-8"))
    return {MANIFEST: render_manifest(product, current), PRODUCT_JS: render_product_js(product)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    drifted = []
    for path, text in derived(load()).items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        drifted.append(path.relative_to(ROOT).as_posix())
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")

    if args.check and drifted:
        print("out of sync with product.toml (run tools/sync_product.py):", *drifted, sep="\n  ")
        return 1
    print("updated: " + ", ".join(drifted) if drifted else "derived files in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
